import json


def side(label, effects, result=None, risk=None, flags=None):
    s = {"label": label, "effects": effects}
    if flags:
        s["set_flags"] = flags
    if result:
        s["result"] = result
    if risk:
        s["risk"] = {"chance": risk[0], "effects": risk[1], "result": risk[2]}
    return s


def card(cid, text, ages, req, left, right, up, room="living", weight=None):
    c = {"id": cid, "text": text, "ages": ages, "room": room}
    if req:
        c["requires"] = req
    if weight:
        c["weight"] = weight
    c["left"], c["right"], c["up"] = left, right, up
    return c


def tier(t):
    return {"fame_tier": [t, t]}


def chain(flag, years, **more):
    req = {"flags": [flag], "since": {flag: years}}
    req.update(more)
    return req


